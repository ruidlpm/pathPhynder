#!/bin/bash
# Regenerates the Options block in docs/workflow.md (between the BEGIN/END_OPTIONS_BLOCK
# markers) from the live `pathPhynder --help` output, so the docs can't drift from
# the real CLI the way they did before (a stale option, a machine-local default
# path baked in by hand). Run this once before cutting a release, after any
# option_list change in pathPhynder.R.
set -euo pipefail
cd "$(dirname "$0")/.."

HELP_TEXT=$(Rscript pathPhynder.R --help 2>&1 | sed -n '/^Options:/,$p')

# the --reference default is resolved to wherever pathPhynder happens to be
# installed on THIS machine - swap it for a generic placeholder so the docs
# stay portable regardless of who last ran this script
HELP_TEXT=$(echo "$HELP_TEXT" | sed -E 's#\[default "[^"]*/data/reference_sequences/hs37d5_Y\.fa\.gz"\]#[default "<path_to_pathPhynder_folder>/data/reference_sequences/hs37d5_Y.fa.gz"]#')

HELP_TEXT="$HELP_TEXT" python3 - docs/workflow.md <<'EOF'
import os, re, sys

doc_path = sys.argv[1]
help_text = os.environ["HELP_TEXT"].rstrip("\n")

with open(doc_path) as f:
    content = f.read()

begin_marker = "<!-- BEGIN_OPTIONS_BLOCK: auto-generated by scripts/update_workflow_options.sh from `pathPhynder --help` - do not hand-edit between these markers, run the script instead -->"
end_marker = "<!-- END_OPTIONS_BLOCK -->"

pattern = re.compile(re.escape(begin_marker) + r".*?" + re.escape(end_marker), re.S)
if not pattern.search(content):
    sys.exit("Could not find BEGIN_OPTIONS_BLOCK/END_OPTIONS_BLOCK markers in " + doc_path)

replacement = begin_marker + "\n```\n" + help_text + "\n\n```\n" + end_marker
updated = pattern.sub(lambda _: replacement, content)

with open(doc_path, "w") as f:
    f.write(updated)

print(doc_path + " Options block regenerated from `pathPhynder --help`.")
EOF
